function readStoredLanguage() {
    try {
        const stored = localStorage.getItem('language');
        return LANGUAGES.includes(stored) ? stored : DEFAULT_LANGUAGE;
    } catch {
        return DEFAULT_LANGUAGE;
    }
}

let language = readStoredLanguage();

export function getLanguage() {
    return language;
}

const LOCALES = { et: 'et-EE', en: 'en-GB', ru: 'ru-RU' };

export function getLocale() {
    return LOCALES[language];
}

export function t(key, params = {}) {
    const text = STRINGS[language][key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function columnLabel(col) {
    return COLUMN_TEXT[language][col]?.label || COLUMN_TEXT[DEFAULT_LANGUAGE][col]?.label || col;
}

// Full column name for header tooltips and conflict details.
export function columnTitle(col) {
    return COLUMN_TEXT[language][col]?.title || col;
}

const ATTRIBUTE_BINDINGS = [
    ['i18nPlaceholder', 'placeholder'],
    ['i18nTooltip', 'data-tooltip'],
    ['i18nAriaLabel', 'aria-label']
];

// Static markup marks translatable text with data-i18n (text), data-i18n-html
// (markup from the dictionary only), and data-i18n-placeholder/-tooltip/-aria-label.
export function applyTranslations(root = document) {
    document.documentElement.lang = language;
    document.title = t('app.title');
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    ATTRIBUTE_BINDINGS.forEach(([dataKey, attribute]) => {
        const selector = '[data-' + dataKey.replace(/[A-Z]/g, c => '-' + c.toLowerCase()) + ']';
        root.querySelectorAll(selector).forEach(el => el.setAttribute(attribute, t(el.dataset[dataKey])));
    });
    root.querySelectorAll('[data-language]').forEach(el => {
        const active = el.dataset.language === language;
        el.classList.toggle('active', active);
        el.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
}

export function setLanguage(next) {
    if (!LANGUAGES.includes(next)) return;
    language = next;
    try {
        localStorage.setItem('language', next);
    } catch {}
    applyTranslations();
    window.dispatchEvent(new CustomEvent('jobs-language-changed', { detail: { language } }));
}
